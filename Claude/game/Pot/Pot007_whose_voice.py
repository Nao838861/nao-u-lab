    print("  同じ人が書いたか、違う人が書いたか。")
    print()
    print("  読むこと、それがこのゲームのすべて。")
    print()
    print(f"  {num_rounds}問。")
    print()
    input("  [Enter で始める]")

    score = 0

    for i, pair in enumerate(pairs):
        clear_screen()
        print(f"── 第{i + 1}問 / {num_rounds} ──")
        print()

        show_fragment("ひとつめ", pair["line1"])
        show_fragment("ふたつめ", pair["line2"])

        while True:
            try:
                ans = input("同じ人？ (y/n): ").strip().lower()
                if ans in ("y", "yes", "はい", "同じ"):
                    player_says_same = True
                    break
                elif ans in ("n", "no", "いいえ", "違う"):
                    player_says_same = False
                    break
                else:
                    print("  y（同じ）か n（違う）で答えてください")
            except (EOFError, KeyboardInterrupt):
                print("\n中断。")
                return

        correct = player_says_same == pair["same"]
        if correct:
            score += 1

        print()
        if pair["same"]:
            print(f"  → 同じ人（{pair['v1']}）。", end="")
        else:
            print(f"  → 違う人（{pair['v1']}と{pair['v2']}）。", end="")

        if correct:
            print(" 正解。")
        else:
            print(" 不正解。")

        print(f"  {score}/{i + 1}")
        print()

        if i < num_rounds - 1:
            input("  [Enter で次へ]")

    # --- 結果 ---
    clear_screen()
    print("=" * 44)
    print("  結果")
    print("=" * 44)
    print()
    print(f"  正解: {score}/{num_rounds}")
    print()

    ratio = score / num_rounds
    if ratio >= 1.0:
        print("  完璧。あなたには声が聞こえている。")
    elif ratio >= 0.7:
        print("  いい耳をしている。でも何人か聞き分けられなかった。")
    elif ratio >= 0.5:
        print("  半分。声はまだぼやけて聞こえている。")
    else:
        print("  声は聞こえていなかった。")
        print("  もう一度、読んでみてほしい。今度はゆっくり。")
    print()

    # 正体を明かす
