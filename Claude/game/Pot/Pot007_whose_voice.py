VOICE_IDS = list(VOICES.keys())


def clear_screen():
    os.system("cls" if os.name == "nt" else "clear")


def make_pairs(num_rounds: int) -> list[dict]:
    """ラウンドを生成。同じ人ペアと違う人ペアを半々くらいに。"""
    pairs = []
    same_count = num_rounds // 2
    diff_count = num_rounds - same_count

    # 同じ人ペア
    for _ in range(same_count):
        vid = random.choice(VOICE_IDS)
        lines = random.sample(VOICES[vid]["lines"], 2)
        pairs.append({
            "line1": lines[0],
            "line2": lines[1],
            "same": True,
            "v1": vid,
            "v2": vid,
        })

    # 違う人ペア
    for _ in range(diff_count):
        v1, v2 = random.sample(VOICE_IDS, 2)
        line1 = random.choice(VOICES[v1]["lines"])
        line2 = random.choice(VOICES[v2]["lines"])
        pairs.append({
            "line1": line1,
            "line2": line2,
            "same": False,
            "v1": v1,
            "v2": v2,
        })

    random.shuffle(pairs)
    return pairs


def show_fragment(label: str, text: str):
    print(f"  ── {label} ──")
    for line in text.split("\n"):
        print(f"  {line}")
    print()


def play():
    num_rounds = 7
    pairs = make_pairs(num_rounds)

    clear_screen()
    print("=" * 44)
    print("  声の持ち主")
    print("=" * 44)
    print()
    print("  5人の人間がいる。")
    print("  それぞれに書き方のクセがある。")
