#         「同じ場所を別の角度から守っている」事実として外から確定する
#   衝突: 映像は二人の供述の **間の空白** を埋めるが、その空白の埋まり方が
#         二人の譲れない筋そのものの形をしている
#   結果: 修平の即時自認（C165）も詩織の「たまに」一語の漏れ（C166）も
#         **被疑者の口からではなく、物証側から先に確定** していたと露見する
# 設計仮説: サイレンススズカテスト（C172 brainstorm §8 候補）— 収束側の試金石
#   サプライズニンジャ（発散側、修平・召喚 C165）の対の角度として、
#   事実を 99% 積層して 1% の決定的観測点で突破する構造を試す
#   キーは「事実の積み方」そのものが物語化すること（被疑者の動きに頼らない）
# 自警プロンプト3問（運用3回目、同型再現性確認）:
#   1. 物証側の事実を地の文で「整理」していないか（並べるだけで整理しない）
#   2. 修平・詩織が既に見せた振る舞いを、映像で再説明していないか
#   3. 整理を出すなら、整理した瞬間にニンジャ（予想破壊観測点）を投入できるか
# brainstorm 借用: Obra Dinn（事実積層型推理）/ 13 Sentinels（時系列交差）
#                  / Disco Elysium（失敗の許容）/ L-1 Dwight Swain scene/sequel
