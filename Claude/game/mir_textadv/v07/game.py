def scene_3_evidence(state: State):
    clear()
    print("第三セット：取調 3日目 14:02  ／  物証・固め")
    print("─" * 40)
    print()
    # 自警1: 「物証連鎖が完成した」と地の文で書かない。事実を並べるだけ。
    print("防犯カメラ映像確認室。被疑者は呼んでいない。")
    print("テーブルの上には、3つのモニタと、43分間のタイムラインだけがある。")
    print()
    print("    1:07  コンビニ店舗カメラ：レシート発行、修平の退店")
    print("    1:23  通り抜け路地のカメラ：徒歩で被害者宅方向へ")
    print("    1:31  被害者宅前の電柱カメラ：到着、玄関先に立つ")
    print("    1:34  同：踵を返す、来た道を戻る方向")
    print("    1:50  （死亡推定時刻）")
    print()
    pause()

    clear()
    # 自警2: 修平の「引き返した」は C165 で既に語られている。再説明しない。
    # 代わりに、**詩織側のカメラ** を出す。これは C166 までに登場していない事実。
    print("もう1台、確認していないカメラがあった。")
    print("詩織のマンションのエントランス。集合住宅の管理カメラ。")
    print()
    print("    1:38  詩織、エントランスから一歩外に出る")
    print("    1:39  同、立ち止まる、通りの先を見る")
    print("    1:41  同、エントランス内に戻る")
    print()
    print("    1:42  （詩織 → 修平：『いまどこ？』送信）")
    print()
    # ニンジャ的瞬間（自警3）: プレイヤーは「詩織は家にいた」を6回聞いている。
    # その語りの **3分前**、彼女がエントランスから一歩出ていた事実が、
    # カメラ側から確定する。被疑者は何も語っていない。物証だけが語る。
    print("『あの夜は一人で家にいた』の供述には、")
    print("家から一歩も出ていないとは、一言も含まれていなかった。")
    print()
    print("彼女は、家から一歩出て、修平が **引き返した方向** を見た。")
    print("そして家に戻り、3分後に『いまどこ？』を送った。")
    print()
    state.evidence_chain_locked = True  # 物証連鎖が二人分そろう
    pause()

    clear()
    # ジレンマ: 両方とも前進する選択肢2つ
    # C173 改稿: メタ整理3行 → 修平パス末尾と韻を踏む描写1行へ圧縮（引き算優先）
    print("二人の譲れない筋が、同じ一点を別の方向から守っていた事実が、")
    print("誰の口も経由せずに、机の上に残った。")
    print()
    c = choose([
        "二人を同席させ、二つのカメラ映像を同じ画面で見せる（譲れない筋を対面させる）",
        "詩織と修平、それぞれに別個に映像を見せ、語らせる（譲れない筋を個別に温存する）",
    ])
    print()

    if c == 1:
        # 対面: 物証で確定した筋の形を、二人の前に同時に置く
        state.collision_named = True
        state.touched_axis_past = True
        state.trust_change(-4)
        print("「お二人に、同じ画面を見ていただきます」")
        print("録画再生の準備を整えながら、")
        print("私は、これから起きることを既に二人より先に知っている顔をしないよう、")
        print("意識的に、表情の角度を一段下げた。")
    else:
        # 個別: 物証で確定した筋の形を、二人それぞれの側に返す
        state.touched_axis_past = True
        state.trust_change(+1)
        print("「映像を、お一人ずつ確認していただきます」")
        print("詩織が先か、修平が先か。")
        print("どちらを先に呼ぶかが、")
        print("この後の『二人の語り』の順序を決める。")
    pause()


