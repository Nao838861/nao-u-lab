    clear()
    print("第四セット：取調 4日目 10:30  ／  対面")
    print("─" * 40)
    print()
    state.confrontation_opened = True

    # 場の立ち上げ: これまで片方ずつだった構造が両被疑者の側にも開く瞬間。
