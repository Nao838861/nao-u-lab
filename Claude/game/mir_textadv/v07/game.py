def clear():
    os.system('cls' if os.name == 'nt' else 'clear')


def pause(prompt="\n[Enter]"):
    try:
        input(prompt)
    except EOFError:
        pass


def choose(options):
    """両方とも前進する選択肢2つ（brainstorm §3 シークエル.ジレンマ）"""
    print()
    for i, label in enumerate(options, 1):
        print(f"  [ {i}. {label} ]")
    print()
    while True:
        try:
            c = int(input("  > "))
            if 1 <= c <= len(options):
                return c
        except ValueError:
            pass
        except EOFError:
            return 1  # 非対話実行時のデフォルト


