def clear():
    os.system('cls' if os.name == 'nt' else 'clear')


def pause(prompt="\n[Enter]"):
    try:
        input(prompt)
    except EOFError:
        pass


def choose(options):
    """両方とも前進する選択肢2つ（brainstorm §3 シークエル.ジレンマ）"""
    print()
    for i, label in enumerate(options, 1):
        print(f"  [ {i}. {label} ]")
    print()
    while True:
        try:
            c = int(input("  > "))
            if 1 <= c <= len(options):
                return c
        except ValueError:
            pass
        except EOFError:
            return 1  # 非対話実行時のデフォルト


# ---------------------------------------------------------------------------
# State
# ---------------------------------------------------------------------------
class State:
    def __init__(self):
        self.trust = 50           # 信頼ゲージ（v01 継承）
        # 第二層フラグ: 譲れない筋に手をかけたか
        self.touched_axis_past = False  # 修平の現場近接の事実に触れたか
        # 第一層フラグ: 矛盾を掴んだか
        self.caught_shift_leak = False  # シフト時間の漏れに気づいたか
        # C161 セット2 追加フラグ
        self.exposed_shuhei_alibi = False  # 修平のアリバイ崩し（店長証言突きつけ）が露見したか
        self.summoned_shuhei = False        # 修平本人を呼ぶ判断を取ったか
        # C163 セット2 物証パス追加フラグ
        self.shown_receipt = False          # 詩織に現場レシートを見せて反応を取ったか
        self.evidence_chain_locked = False  # 物証連鎖を裏取りで固めたか（外堀完成）
        # C165 セット3 修平・召喚パス追加フラグ
        self.shuhei_self_offered = False    # 修平が自分から事件夜の現場近接を差し出したか
        self.collision_named = False        # 詩織と修平の譲れない筋の衝突を、刑事が名指ししたか

    def trust_change(self, d):
        self.trust = max(0, min(100, self.trust + d))


