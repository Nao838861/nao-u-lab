def sequel_3_evidence(state: State):
    clear()
    print("─" * 40)
    print("取調を一時中断。")
    print()
    if state.collision_named:
        print("二つの映像を同時に見せる準備が整った。")
        print("詩織と修平の譲れない筋は、物証側で既に同じ点に交差している。")
        print("対面で起きるのは、その交差を二人が **同時に見る** 瞬間だけだ。")
    else:
        print("二人それぞれに映像を返す準備が整った。")
        print("先に呼ぶ側に、物証が確定させた筋の形が、")
        print("もう一方の側より一拍早く見える。")
    print()

    print("次に、どこへ進む？")
    c = choose([
        "対面シーンで、二つの映像を同じ画面に並べて再生する",
        "通話履歴を全展開し、6か月分の送信パターンを物証連鎖に重ねる",
    ])
    print()

    if c == 1:
        next_setup = "対面"
        print("「お二人とも、同じ部屋にお呼びします」")
        print("詩織側の手帳には『姉が一歩外に出た事実』が、")
