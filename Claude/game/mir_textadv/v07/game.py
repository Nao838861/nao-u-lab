        print("呼吸を、合わせるでも、外すでもなく、")
        print("ただ、場のリズムに残した。")
        print()
        print("詩織は、視線を一度落とし、もう一度上げた。")
        print("「……修平を、待ちます」")
        print()
        print("18秒。それが、最初の沈黙の長さだった。")
        print("わたしは、その18秒を、手帳に記録しなかった。")
