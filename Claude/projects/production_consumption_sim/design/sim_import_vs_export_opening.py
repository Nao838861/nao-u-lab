# 訂正版: 木こりの収入=内部経済(丸太→製材所→材木→建設/道具)、序盤は輸出でなく輸入国
# 島内金の推移を「間違ったモデル(輸出洪水)」vs「正しいモデル(内部循環+輸入ドレイン)」で比較

DAYS=100

# 共通: 内部循環は島内金を変えない(世帯↔世帯で金が動くだけ・保存)
# 島内金を変えるのは: 移民持参金(+), 本国支援=信用で財が来る(金は動かない), 
#                    輸入品購入(-, 島→本国), 輸出売却(+, 本国→島)

def sim(label, mode):
    M=910.0            # 初期島内金(初期資本+種3世帯)
    credit=0.0
    pop=28
    print(f"\n--- {label} ---")
    print(f"{'日':>4}{'人口':>5}{'島内金':>8}{'信用':>7}  メモ")
    for day in range(0,DAYS+1):
        note=""
        # 移民(12日周期・持参金35)
        if day>0 and day%12==0:
            M+=35; pop+=8; note="移民+35"
        if mode=='wrong':
            # 間違い: Day0から木材を会社がマージン輸出→毎日金が注入(排水口なし)
            export_rev = pop*0.15*4.2   # 人口比例の木材輸出売上(本国→島)
            M += export_rev
            note += f" 輸出注入+{export_rev:.0f}"
        else:
            # 正しい: 輸出なし。必需の輸入品(鉄道具など)を高額で買う→島→本国へ流出
            #         序盤ほど自給できず輸入依存, 支援は信用で財が来る(金は減らない)
            import_drain = pop*0.12*8.0 * max(0.2, 1 - day/120)  # 自給が進むほど輸入減
            M -= import_drain
            note += f" 輸入ドレイン-{import_drain:.0f}"
            if day<36 and day%12==0:
                credit += 60*6; note+=" 支援(信用+360)"
            # 資本が尽きたら支援=信用に頼る(前借り)
            if M<0:
                borrow=-M+100; credit+=borrow; M+=borrow; note+=f" 緊急前借り+{borrow:.0f}"
        if day%10==0 or note:
            print(f"{day:>4}{pop:>5}{M:>8.0f}{credit:>7.0f}  {note}")
    return M

m_wrong=sim("間違ったモデル(Day0から輸出・排水口なし)", 'wrong')
m_right=sim("正しいモデル(輸出なし・内部循環+輸入ドレイン・支援は信用)", 'right')
print(f"\n=== 比較 ===")
print(f"間違い: 島内金 910 → {m_wrong:.0f} (洪水)")
print(f"正しい: 島内金 910 → {m_right:.0f} (乏しく管理が要る=良い緊張)")
print("木こりの収入は両モデルとも内部経済(丸太→製材所→材木)から。会社金とは無関係。")
