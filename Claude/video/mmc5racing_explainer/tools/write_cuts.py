def main():
    old = {}
    if P.exists():
        old = {c['id']: c for c in json.loads(P.read_text(encoding='utf-8'))['cuts']}
    cuts = []
    prev_ch = None
    for cid, ch, title, text in CUTS:
        c = {
            'id': cid, 'chapter': ch, 'title': title, 'text': text,
            'instructions': '原稿の全ての文を順番に読み、省略や言い換えをしないでください。「×」は「かける」と読んでください。',
            'startFrame': 0, 'durationFrames': 300, 'minimumDurationFrames': 0,
            # 章の最初のカットは章タイトルを見せる時間を先に取る
            'narrationLeadFrames': 54 if ch != prev_ch and cid != 'C01' else 12,
        }
        o = old.get(cid)
        if o and o.get('text') == text and 'measuredDurationSeconds' in o:
            c['measuredDurationSeconds'] = o['measuredDurationSeconds']
        cuts.append(c)
        prev_ch = ch
    cuts.append({'id': 'C23', 'chapter': CH5, 'title': '', 'text': '', 'silent': True,
                 'startFrame': 0, 'durationFrames': 210, 'minimumDurationFrames': 210, 'narrationLeadFrames': 0})
    manifest = {
        'model': 'gpt-4o-mini-tts-2025-12-15', 'voice': 'marin', 'speed': 1.2, 'responseFormat': 'wav',
        'commonInstructions': '日本語の技術解説動画のナレーションです。同じナレーターが一続きで説明しているように、全カットで話速、声の高さ、音量、文末の調子を揃えてください。'
                              '落ち着いた自然な標準語で、文中では急に加速・減速せず、語句と助詞を滑らかにつなげてください。句読点に応じた自然な間を置き、平叙文の語尾は疑問調にせず自然に着地させてください。'
                              '固有名詞、数値、英字も文脈に沿って自然につなげ、大げさな演技、広告調、一本調子にはしないでください。音声だけを出力し、前後に長い無音を入れないでください。',
        'fps': 30, 'tailPaddingSeconds': 0.45, 'outputDirectory': 'narration', 'reportFileName': 'duration-report.json',
        'silenceCompaction': {'preserveInternalSilence': True, 'maximumLeadingSilenceMs': 20, 'maximumTrailingSilenceMs': 100},
        'cuts': cuts,
    }
    P.parent.mkdir(exist_ok=True)
    P.write_text(json.dumps(manifest, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    print(len(cuts), 'cuts')


if __name__ == '__main__':
    main()
