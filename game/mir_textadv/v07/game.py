#!/usr/bin/env python3
"""mir_textadv_07 — 取調室（第二層主軸: キャラの譲れない筋）

v07 設計の主軸: 第一層（設定・年表・能力の論理一貫性）ではなく
第二層（キャラの譲れない筋）を AI が保持する設計仮説の検証。

参照:
  brainstorm.md §0 第二層主軸宣言 / §2 4素材 / §3 取調1セット最小単位
  devlog.md C148 v01「矛盾外発露出の瞬間」を Q-A 対象に据える

C160 (2026-05-06) 第1セット実装。粒度規律: 1サイクル1セット。
本ファイルは「被疑者1名・譲れない筋1つ・矛盾1つ・選択肢2つ」の最小単位のみ。
セット2以降は次サイクル。
"""

import os

# ---------------------------------------------------------------------------
# 譲れない筋（被疑者ごと、3項3行以内 - brainstorm §2 素材1）
# ---------------------------------------------------------------------------
# 橘詩織（v01 継承の被疑者、ただし「譲れない筋」を v07 で初めて明文化）
SHIORI_AXIS = {
    "信条": "弟・修平が誰よりも先に守られるべき",
    "関係": "母を死なせた父との和解は絶対にしない",
    "過去": "事件の夜、修平が現場近くにいたことだけは隠す",
}

# 第一セットの「譲れない筋」focus: 過去（修平の現場近くにいた事実）
# 矛盾の種: 詩織は「あの夜は一人だった」と言うが、被害者宅から徒歩5分の
# 修平のバイト先のシフト時間を、聞かれてもいないのに口にしてしまう。

# ---------------------------------------------------------------------------
# UI 基本部品（v01 から継承）
# ---------------------------------------------------------------------------
def clear():
    os.system('cls' if os.name == 'nt' else 'clear')


def pause(prompt="\n[Enter]"):
    try:
        input(prompt)
    except EOFError:
        pass


def choose(options):
    """両方とも前進する選択肢2つ（brainstorm §3 シークエル.ジレンマ）"""
    print()
    for i, label in enumerate(options, 1):
        print(f"  [ {i}. {label} ]")
    print()
    while True:
        try:
            c = int(input("  > "))
            if 1 <= c <= len(options):
                return c
        except ValueError:
            pass
        except EOFError:
            return 1  # 非対話実行時のデフォルト


# ---------------------------------------------------------------------------
# State
# ---------------------------------------------------------------------------
class State:
    def __init__(self):
        self.trust = 50           # 信頼ゲージ（v01 継承）
        # 第二層フラグ: 譲れない筋に手をかけたか
        self.touched_axis_past = False  # 修平の現場近接の事実に触れたか
        # 第一層フラグ: 矛盾を掴んだか
        self.caught_shift_leak = False  # シフト時間の漏れに気づいたか

    def trust_change(self, d):
        self.trust = max(0, min(100, self.trust + d))


# ---------------------------------------------------------------------------
# シーン1: 譲れない筋（過去）を引き出す
#   目標: 詩織から「修平が現場近くにいた」事実を引き出す
#   衝突: 詩織は譲れない筋を直接語らない。供述に矛盾の種を混ぜる
#   結果: プレイヤーは矛盾を掴むか/泳がせるか判断 → 信頼ゲージ変動
# ---------------------------------------------------------------------------
def scene_1(state: State):
    clear()
    print("第一セット：取調 1日目 22:14")
    print("─" * 40)
    print()
    # 情報非対称性（devlog L-1 #2）: プレイヤーは事件発生時刻 1:50-2:30 を既知
    print("被害者・野上誠一の死亡推定時刻は午前1時50分から2時30分。")
    print("橘詩織は『あの夜は一人で家にいた』と最初の供述で言っている。")
    print()
    pause()

    clear()
    print("詩織はテーブルに視線を落としたまま、ぽつりと言った。")
    print()
    # 矛盾の種: 聞かれていないのに修平のシフト時間を口にする
    print("「……あの時間、わたし、ずっと家にいました。")
    print("  修平のバイトが終わるのが2時だから、それまでには寝ようと思って」")
    print()
    print("彼女は『修平のバイトが終わるのが2時』と言った。")
    print("聞いていない。彼女は弟の話題を、こちらが振る前に出した。")
    print()
    # シーン.結果: 突きつけるか/泳がせるか
    c = choose([
        "「修平さんのシフトの話は、まだ訊いていませんが」と突きつける",
        "頷いて聞き流し、別の角度から修平の話を引き出す",
    ])
    print()

    if c == 1:
        # 突きつけ: 信頼-、譲れない筋に直接手をかける
        state.caught_shift_leak = True
        state.touched_axis_past = True
        state.trust_change(-8)
        print("詩織の指がわずかに震えた。")
        print("「……すみません。関係ないことを」")
        print("壁が一段厚くなった。だが、彼女は『修平』と無意識に口にした。")
        print("守る対象が誰かは、もう露見している。")
    else:
        # 泳がせ: 信頼+、譲れない筋の輪郭を温存
        state.caught_shift_leak = True  # 気づきは記録（プレイヤー内部のみ）
        state.touched_axis_past = False
        state.trust_change(+4)
        print("「修平さんは、よく深夜勤務を？」")
        print("「ええ。コンビニの夜勤で。最近は週4日です」")
        print("彼女は普通に答えた。だが先ほどの『2時』は、")
        print("私の手帳の片隅に小さく残った。")
    pause()


# ---------------------------------------------------------------------------
# シークエル1: 反応・ジレンマ・決断（brainstorm §3 後半）
# ---------------------------------------------------------------------------
def sequel_1(state: State):
    clear()
    print("─" * 40)
    print("取調を一時中断。隣室で記録を見直す。")
    print()
    # 反応: 場の緊張変化（1-2行）
    if state.touched_axis_past:
        print("詩織は弟の名前を出した瞬間、明らかに身を縮めた。")
        print("守る対象は弟・修平。ここは触れれば崩れる場所だ。")
    else:
        print("詩織は弟の話題に普通に応じた。だが『2時』の漏れは消えない。")
        print("彼女が守ろうとしているものの輪郭は、まだ私の側にある。")
    print()

    # ジレンマ: 両方とも前進する選択肢2つ
    print("次に何を聞く？")
    c = choose([
        "弟・修平のあの夜の足取りを直接訊く（譲れない筋に手を伸ばす）",
        "事件現場の物証から固める（譲れない筋を温存して外堀を埋める）",
    ])
    print()

    # 決断: 次シーンの目標を決定
    if c == 1:
        next_target = "修平の足取り"
        print("「修平さんは、あの夜どこにいましたか」")
        print("詩織の呼吸が、ほんの一瞬止まった。")
    else:
        next_target = "現場の物証"
        print("「現場で気になるものが見つかっています」")
        print("詩織は『はい』と答えた。だが目線は、こちらの手帳に走った。")
    pause()
    return next_target


# ---------------------------------------------------------------------------
# 章末フック: 次セットの予告（ページターナー理論、brainstorm §2 素材3）
# ---------------------------------------------------------------------------
def chapter_hook(state: State, next_target: str):
    clear()
    print("─" * 40)
    print("第一セット 終了")
    print()
    if next_target == "修平の足取り":
        print("次セット予告：詩織の譲れない筋・修平の現場近接が、明日の取調で試される。")
    else:
        print("次セット予告：現場で見つかった物証が、詩織の供述と噛み合うか試される。")
    print()
    print(f"信頼ゲージ: {state.trust}")
    if state.caught_shift_leak:
        print("手帳の隅: 『2時 / 修平のシフト』")
    print()
    print("(C160 セット1終了。セット2以降は次サイクル実装)")
    print()


# ---------------------------------------------------------------------------
# main
# ---------------------------------------------------------------------------
def main():
    state = State()
    scene_1(state)
    next_target = sequel_1(state)
    chapter_hook(state, next_target)


if __name__ == "__main__":
    main()
